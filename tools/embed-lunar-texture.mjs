import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
const source = new URL('../dist/assets/lunar-regolith.png', import.meta.url);
const target = new URL('../dist/lunar-regolith-asset.js', import.meta.url);
const bytes = fs.readFileSync(source);
if (!bytes.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]))) throw new Error('Expected the authored lunar PNG');
const text = '// Generated by tools/embed-lunar-texture.mjs; edit the PNG source instead.\n' +
  '// Artistic material detail, not NASA imagery or measured surface data.\n' +
  'export const lunarRegolithDataURL = ' + JSON.stringify('data:image/png;base64,' + bytes.toString('base64')) + ';\n';
if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== text) fs.writeFileSync(target, text);
console.log('Embedded lunar material:', fileURLToPath(source));
